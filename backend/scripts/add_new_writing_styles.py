async def add_new_writing_styles():
    """添加新写作风格到数据库"""
    # 获取共享数据库引擎
    engine = await get_engine("system")  # 使用固定用户ID获取共享引擎

    # 创建会话工厂
    AsyncSessionLocal = async_sessionmaker(
        engine,
        class_=AsyncSession,
        expire_on_commit=False
    )

    async with AsyncSessionLocal() as db:
        # 检查现有预设风格
        result = await db.execute(
            select(WritingStyle)
            .where(WritingStyle.user_id.is_(None))
            .order_by(WritingStyle.order_index)
        )
        existing_presets = result.scalars().all()
        existing_preset_ids = {p.preset_id for p in existing_presets}

        print(f"现有预设风格数量: {len(existing_presets)}")
        print(f"现有 preset_ids: {existing_preset_ids}")

        # 添加新风格
        added_count = 0
        skipped_count = 0

        for style_data in NEW_WRITING_STYLES:
            preset_id = style_data["preset_id"]

            # 检查是否已存在
            if preset_id in existing_preset_ids:
                print(f"⚠️  风格 '{style_data['name']}' (preset_id: {preset_id}) 已存在，跳过")
                skipped_count += 1
                continue

            # 创建新风格
            new_style = WritingStyle(
                user_id=None,  # 全局预设风格
                preset_id=preset_id,
                name=style_data["name"],
                description=style_data["description"],
                prompt_content=style_data["prompt_content"],
                style_type="preset",
                order_index=style_data["order_index"],
            )

            db.add(new_style)
            added_count += 1
            print(f"✅ 添加风格: {style_data['name']} (preset_id: {preset_id})")

        # 提交更改
        if added_count > 0:
            await db.commit()
            print(f"\n✨ 成功添加 {added_count} 种新写作风格")
        else:
            print(f"\nℹ️  没有新风格需要添加")

        if skipped_count > 0:
            print(f"⏭️  跳过 {skipped_count} 个已存在的风格")


async def main():
    """主函数"""
    print("=" * 60)
    print("📚 上架新写作风格到数据库")
    print("=" * 60)
    print()

    try:
        await add_new_writing_styles()
        print("\n✅ 完成！")
    except Exception as e:
        print(f"\n❌ 错误: {e}")
        raise


if __name__ == "__main__":
    asyncio.run(main())
